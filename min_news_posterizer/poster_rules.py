POSTER_RULES = """COMPOSITION:
- One clear focal point: the main person or actor from the scene; a real public figure may appear only stylized in the chosen art style, never photorealistic.
- The story's place as background and 1-3 key objects as visual symbols.
- Keep a clean, uncluttered area for the headline so it reads at a glance on a small screen."""
